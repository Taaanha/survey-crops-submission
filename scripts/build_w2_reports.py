import os
import sys

import numpy as np
import pandas as pd

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
sys.path.insert(0, os.path.join(ROOT, "src", "compute"))
from change_point import pettitt_test  # noqa: E402
from indicators.ground import (bias_table, monthly_mean_rain, monthly_mean_temp, temp_bias_table,
                               temperature_normals)  # noqa: E402
from indicators.trend import trend_status  # noqa: E402
from reference import load_reference  # noqa: E402
from weather import load_weather  # noqa: E402

DATA = os.path.join(ROOT, "data", "processed")
RES = os.path.join(ROOT, "docs", "results")
STATIONS = {"comilla": "cumilla", "feni": "feni", "maijdi_court": "noakhali", "sylhet": "sylhet"}
TEMP_KEY = {"comilla": "cumilla"}  # the temperature file spells Comilla "cumilla"; the rain file "comilla"
STATION_NAME = {"comilla": "Comilla", "feni": "Feni", "maijdi_court": "Maijdi Court (Noakhali)", "sylhet": "Sylhet"}
MONTHS = ["jan", "feb", "mar", "apr", "may", "jun", "jul", "aug", "sep", "oct", "nov", "dec"]
YEARS = range(2001, 2025)
LIVE = ["cumilla", "feni", "brahmanbaria", "noakhali", "sylhet"]


def ground_check():
    ref = load_reference(files=["bmd_normal_rainfall.csv"]).kept.set_index("item")
    rows = []
    for station, district in STATIONS.items():
        normal = pd.Series([float(ref.loc[f"{station}.normal_rain_{m}", "value"]) for m in MONTHS], index=range(1, 13))
        for source in ("imerg", "power"):
            w = load_weather(district, rain_source=source)["rainfall_mm"]
            t = bias_table(monthly_mean_rain(w, YEARS), normal)
            t.index = t.index.map(str)
            t = t.reset_index(names="month")
            t.insert(0, "source", source.upper())
            t.insert(0, "district", district)
            t.insert(0, "station", station)
            rows.append(t)
    return pd.concat(rows, ignore_index=True), ref


def fmt(x, d=0):
    return "n/a" if pd.isna(x) else f"{x:.{d}f}"


def write_ground(t, ref):
    t.to_csv(os.path.join(RES, "w2_ground_check.csv"), index=False, float_format="%.3f")
    src = ref.iloc[0]
    L = ["# W2 satellite vs ground check: rain against BMD monthly normals", "",
         "Generated by `scripts/build_w2_reports.py`. Do not edit by hand; re-run the script.", "",
         f"Ground: {src['source_title']}, {src['source_url']} (stations Comilla, Feni, Maijdi Court = Noakhali, Sylhet; "
         "no Brahmanbaria station in the table). Satellite: NASA GPM IMERG V07 Final Run daily "
         "(`GPM_3IMERGDF.07`, 0.1 degree cell at the district point) and NASA POWER daily `PRECTOTCORR` (about 0.5 degree), "
         "monthly means of 2001-2024 (24 years, every day of a month observed). Bias = satellite minus BMD normal; "
         "percent is of the normal.", "",
         "## Caveats (read before using the numbers)", "",
         "- **The BMD table does not state its averaging period**, so the normal and our 2001-2024 mean may cover different years. "
         "A difference can be climate change or natural swings, not only satellite error.",
         "- A station is a point; IMERG is a 0.1 degree cell (about 11 km) and POWER about 0.5 degree. The district point we use is "
         "not the station site, so some of the bias is distance.",
         "- Four stations is a small check, not a validation of every district. This says nothing about Brahmanbaria.",
         "- Monthly means only: daily accuracy and heavy-rain days are not checked here.", "",
         "## Annual totals", "",
         "| Station | BMD normal (mm) | IMERG (mm) | IMERG bias | POWER (mm) | POWER bias |", "|---|---|---|---|---|---|"]
    a = t[t.month == "annual"].set_index(["station", "source"])
    for st in STATIONS:
        i, p = a.loc[(st, "IMERG")], a.loc[(st, "POWER")]
        L.append(f"| {STATION_NAME[st]} | {fmt(i.normal_mm)} | {fmt(i.satellite_mm)} | {fmt(i.bias_mm):>4} mm ({fmt(i.bias_pct, 1)}%) | "
                 f"{fmt(p.satellite_mm)} | {fmt(p.bias_mm)} mm ({fmt(p.bias_pct, 1)}%) |")
    m = t[t.month != "annual"].assign(abs_mm=lambda d: d.bias_mm.abs())
    s = m.groupby(["station", "source"]).abs_mm.mean().unstack()
    closer = [STATION_NAME[st] for st in STATIONS if s.loc[st, "IMERG"] < s.loc[st, "POWER"]]
    ia = a.xs("IMERG", level="source")
    low = [STATION_NAME[st] for st in STATIONS if ia.loc[st, "bias_pct"] < -10]
    summary = ["## Summary", "",
               f"- IMERG annual totals are more than 10% below the BMD normal at {len(low)} of 4 stations ({', '.join(low) or 'none'}); "
               f"Comilla is {fmt(ia.loc['comilla', 'bias_pct'], 1)}%.",
               f"- By mean absolute monthly bias, IMERG is closer to BMD than POWER at {len(closer)} of 4 stations"
               f"{' (' + ', '.join(closer) + ')' if closer else ''}. **On this check the satellite is not better than POWER on bias.**",
               "- This does not reverse the choice of IMERG as the rain source: POWER rain has level shifts around 2014-15 "
               "(`w2_homogeneity.md`, T9b), so its 2001-2024 mean mixes a low early level with a high late level and can land "
               "near a normal by offset, not by being right. A steady bias like IMERG's low monsoon months is easier to state than a jump.",
               "- Because IMERG tends to read low against these normals, rain totals and dry-spell counts from IMERG should be read "
               "as estimates from NASA data for the area around the point, not as station rain.", ""]
    L[L.index("## Annual totals"):L.index("## Annual totals")] = summary
    L += ["", "## Mean absolute monthly bias (mm per month)", "", "| Station | IMERG | POWER | closer to BMD |", "|---|---|---|---|"]
    for st in STATIONS:
        better = "IMERG" if s.loc[st, "IMERG"] < s.loc[st, "POWER"] else "POWER"
        L.append(f"| {STATION_NAME[st]} | {s.loc[st, 'IMERG']:.1f} | {s.loc[st, 'POWER']:.1f} | {better} |")
    L += ["", "## Monthly bias (percent of the BMD normal; mm in brackets)", ""]
    for source in ("IMERG", "POWER"):
        L += [f"**{source}**", "", "| Month | " + " | ".join(STATION_NAME[s_] for s_ in STATIONS) + " |",
              "|---|" + "---|" * len(STATIONS)]
        for k in range(1, 13):
            cells = []
            for st in STATIONS:
                r = t[(t.station == st) & (t.source == source) & (t.month == str(k))].iloc[0]
                cells.append(f"{fmt(r.bias_pct)}% ({fmt(r.bias_mm)})")
            L.append(f"| {MONTHS[k - 1].capitalize()} | " + " | ".join(cells) + " |")
        L.append("")
    worst = m[m.source == "IMERG"].sort_values("abs_mm", ascending=False).head(3)
    L += ["## Where the satellite is worst", "",
          "The three largest IMERG monthly misses: " + "; ".join(
              f"{STATION_NAME[r.station]} {MONTHS[int(r.month) - 1].capitalize()} {fmt(r.bias_mm)} mm ({fmt(r.bias_pct)}%)"
              for r in worst.itertuples()) + ".", ""]
    open(os.path.join(RES, "w2_ground_check.md"), "w", encoding="utf-8").write("\n".join(L))


def temperature_check():
    """POWER Tmax and Tmin vs BMD (MET Norway report) monthly normals, 2001-2024, four stations."""
    ref = load_reference(files=["bmd_normal_temperature.csv"]).kept
    rows = []
    for station, district in STATIONS.items():
        w = load_weather(district)
        for kind, col in (("tmax", "temp_max_c"), ("tmin", "temp_min_c")):
            t = temp_bias_table(monthly_mean_temp(w[col], YEARS), temperature_normals(ref, TEMP_KEY.get(station, station), kind))
            t.index = t.index.map(str)
            t = t.reset_index(names="month")
            t.insert(0, "kind", kind)
            t.insert(0, "district", district)
            t.insert(0, "station", station)
            rows.append(t)
    return pd.concat(rows, ignore_index=True), ref


def write_temperature(t, ref):
    t.to_csv(os.path.join(RES, "w2_temperature_check.csv"), index=False, float_format="%.3f")
    src = ref.iloc[0]
    period = [n for n in ref["notes"].str.extract(r"(Period \d{4}-\d{4})")[0].dropna().unique()]
    L = ["# W2 POWER temperature vs BMD normals", "", "Generated by `scripts/build_w2_reports.py`. Do not edit by hand; re-run the script.", "",
         f"Ground: {src['source_title']}, {src['source_url']}, page {src['page']}. Model: NASA POWER daily `T2M_MAX` / `T2M_MIN` "
         "(AG community, about 0.5 degree cell at the district point), monthly means of 2001-2024 (every day of a month observed). "
         "Bias = POWER minus normal, in degrees C.", "",
         "## Caveats (read before using the numbers)", "",
         f"- **Averaging period:** the normals file states {', '.join(period) or 'no period'} (a MET Norway / BMD report, not a BMD publication). "
         "Our POWER window is 2001-2024, so the two cover different years and part of any bias can be warming, not POWER error. "
         "The BMD rain normals, by contrast, state no period at all.",
         "- A station is a point; POWER is a 0.5 degree cell (about 55 km), so elevation and coast effects inside the cell are averaged out. "
         "Feni and Noakhali share one POWER cell, so their POWER temperatures are identical.",
         "- Four stations is a small check, not a validation of every district; Brahmanbaria has no station.", "",
         "## Annual bias (mean of the 12 monthly biases, degrees C)", "", "| Station | Tmax normal | POWER Tmax | bias | Tmin normal | POWER Tmin | bias |", "|---|---|---|---|---|---|---|"]
    a = t[t.month == "annual"].set_index(["station", "kind"])
    for st in STATIONS:
        x, n = a.loc[(st, "tmax")], a.loc[(st, "tmin")]
        L.append(f"| {STATION_NAME[st]} | {x.normal_c:.1f} | {x.model_c:.1f} | {x.bias_c:+.1f} | {n.normal_c:.1f} | {n.model_c:.1f} | {n.bias_c:+.1f} |")
    m = t[t.month != "annual"].assign(abs_c=lambda d: d.bias_c.abs())
    worst = m.sort_values("abs_c", ascending=False).head(5)
    mae = m.groupby(["station", "kind"]).abs_c.mean().unstack()
    L += ["", "## Mean absolute monthly bias (degrees C)", "", "| Station | Tmax | Tmin |", "|---|---|---|"]
    L += [f"| {STATION_NAME[st]} | {mae.loc[st, 'tmax']:.1f} | {mae.loc[st, 'tmin']:.1f} |" for st in STATIONS]
    L += ["", "## Monthly bias, POWER minus normal (degrees C)", ""]
    for kind in ("tmax", "tmin"):
        L += [f"**{kind.upper()}**", "", "| Month | " + " | ".join(STATION_NAME[s_] for s_ in STATIONS) + " |", "|---|" + "---|" * len(STATIONS)]
        for k in range(1, 13):
            cells = [f"{t[(t.station == st) & (t.kind == kind) & (t.month == str(k))].iloc[0].bias_c:+.1f}" for st in STATIONS]
            L.append(f"| {MONTHS[k - 1].capitalize()} | " + " | ".join(cells) + " |")
        L.append("")
    tx, tn = m[m.kind == "tmax"], m[m.kind == "tmin"]
    cool = int((tx.bias_c < 0).sum())
    L += ["## Where POWER is worse", "",
          "The five largest monthly misses: " + "; ".join(f"{STATION_NAME[r.station]} {r.kind.upper()} {MONTHS[int(r.month) - 1].capitalize()} {r.bias_c:+.1f} C"
                                                         for r in worst.itertuples()) + ".", "",
          f"- **Tmax is the weaker variable**: mean absolute monthly bias {tx.abs_c.mean():.1f} C against {tn.abs_c.mean():.1f} C for Tmin, "
          f"and POWER Tmax is below the normal in {cool} of {len(tx)} station-months. A 1981-2010 normal compared with 2001-2024 data "
          "would make a warmer POWER more likely, so the cool Tmax is not explained by warming.",
          "- A cool Tmax can undercount heat-stress days (days Tmax above a limit), most of all for limits close to the typical Tmax.",
          f"- Tmin is close on the annual mean ({tn.groupby('station').bias_c.mean().abs().max():.1f} C at most), but single months miss by up to "
          f"{tn.abs_c.max():.1f} C, which moves cold-night counts. Read both as estimates from NASA data for the area around the point, "
          "not station records.", ""]
    open(os.path.join(RES, "w2_temperature_check.md"), "w", encoding="utf-8").write("\n".join(L))


def annual(series, years):
    """Calendar-year totals for years whose 365/366 days are all present."""
    out = {}
    for y in years:
        w = series.reindex(pd.date_range(f"{y}-01-01", f"{y}-12-31"))
        out[y] = float(w.sum()) if not w.isna().any() else np.nan
    return out


def show(r):
    if r["status"] == "step_change":
        return f"**step_change**: {r['text']}"
    return f"{r['status']} (slope {r['slope']:+.1f} mm/yr, Kendall p={r['kendall_p']:.2f}, Pettitt p={r['pettitt_p']:.2f}, n={r['n']})"


def write_homogeneity():
    L = ["# W2 homogeneity check: trends, level shifts, and why POWER rain is excluded", "",
         "Generated by `scripts/build_w2_reports.py`. Do not edit by hand; re-run the script.", "",
         "**Method.** For each yearly series: Theil-Sen slope and Kendall tau test; then Pettitt's change-point test on the "
         "detrended residuals. `step_change` (residual Pettitt p < 0.05) means a level shift: it is **not shown as a trend**. "
         "`trend` means Kendall p < 0.05 and no step. 0.05 is a conventional level, our choice, not a requirement from a source. "
         "The Pettitt p-value is an approximation (Pettitt 1979), and the test finds one break at most.", "",
         "## 1. POWER rain vs IMERG rain (annual totals, calendar years)", "",
         "| District | POWER 1981-2025 | POWER 2001-2024 | IMERG 2001-2024 |", "|---|---|---|---|"]
    ratio_rows = []
    for d in LIVE:
        p = load_weather(d, rain_source="power")["rainfall_mm"]
        im = load_weather(d)["rainfall_mm"]
        cells = []
        for s, yrs in ((p, range(1981, 2026)), (p, YEARS), (im, YEARS)):
            a = annual(s, yrs)
            cells.append(show(trend_status(list(a), list(a.values()), unit="mm")))
        L.append(f"| {d.capitalize()} | " + " | ".join(cells) + " |")
        ap, ai = annual(p, YEARS), annual(im, YEARS)
        raw = pettitt_test(list(ap.values()))
        ratio = [ap[y] / ai[y] for y in YEARS]
        rt = pettitt_test(ratio)
        yrs = list(YEARS)
        ratio_rows.append(f"| {d.capitalize()} | {yrs[raw['split']]}, p={raw['p']:.3f} | {yrs[rt['split']]}, p={rt['p']:.4f}, "
                          f"{rt['mean_before']:.2f} -> {rt['mean_after']:.2f} |")
    L += ["", "**Warning about the rule above.** After a straight line is removed, a jump in POWER rain is partly absorbed into the "
          "line, so the residual test can call a broken record a `trend`. The two checks below do not have that weakness: Pettitt on "
          "the raw POWER series, and Pettitt on the ratio POWER / IMERG (with IMERG as the reference, a break in the ratio is a jump "
          "in POWER alone).", "",
          "| District | Pettitt on raw POWER annual (first year after break) | Pettitt on POWER / IMERG ratio (mean before -> after) |",
          "|---|---|---|"] + ratio_rows
    L += ["", "POWER rain contains level shifts (about 2014-15, see `docs/results/rain_source_check.md`, T9b), so it is **not used** "
          "for recommendations, rankings or trends. IMERG is the rain source. This table reuses the same test as T9b on the same "
          "series, with the residual rule above and the two extra checks.", "",
          "## 2. Season trends we use (IMERG rain, POWER temperature, FAO-56 ET0, and the regional GRACE-FO storage signal)", "",
          "Source file: `data/processed/indicators_trends_2001_2024.csv`; 24 seasons (2001-2024) per row, except the GRACE-FO rows (`grace_lwe`: it starts in 2002 and has gaps, so n is in the text; regional, about 300 km, shared cells, never district groundwater).", "",
          "| District | Season | Variable | Result |", "|---|---|---|---|"]
    tr = pd.read_csv(os.path.join(DATA, "indicators_trends_2001_2024.csv"))
    for r in tr.itertuples():
        L.append(f"| {r.district.capitalize()} | {r.season} | {r.variable} | {r.status}: {r.text} |")
    n = len(tr)
    hits = int((tr.status == "trend").sum())
    L += ["", f"**Reading these honestly.** {n} series were tested at the 0.05 level, so about {n * 0.05:.0f} would show up by chance "
          f"alone; {hits} are marked `trend` and {int((tr.status == 'step_change').sum())} `step_change`. Season Tmean and ET0 come "
          "from NASA POWER (about 0.5 degree), and Feni and Noakhali share one POWER cell, so their temperature and ET0 rows are not independent. "
          "We have not checked POWER temperature against an independent station record, so a clean result here shows no level shift "
          "within POWER, not that POWER is right.", ""]
    open(os.path.join(RES, "w2_homogeneity.md"), "w", encoding="utf-8").write("\n".join(L))


if __name__ == "__main__":
    t, ref = ground_check()
